#!/usr/bin/env node
/**
 * Write frontend/.env.production from App Platform / shell env before CRA build.
 * CRA only inlines REACT_APP_* at build time — Run Time env alone is not enough.
 */
const fs = require('fs');
const path = require('path');

const outFile = path.join(__dirname, '..', 'frontend', '.env.production');

const keys = [
  'REACT_APP_API_BASE_URL',
  'REACT_APP_DEFAULT_USER_ID',
  'REACT_APP_DEFAULT_MERCHANT_KEY',
  'REACT_APP_DEFAULT_CENTER',
  'REACT_APP_AUTH_API_URL',
  'REACT_APP_DESKTOP_AUTH_API_URL',
  'REACT_APP_SHOW_SUPERADMIN_LOGIN',
];

const lines = [
  '# Generated by scripts/write-frontend-env.js during npm run build',
];

let missing = [];

for (const key of keys) {
  const raw = process.env[key];
  let value = raw === undefined || raw === null ? '' : String(raw);
  if (key === 'REACT_APP_SHOW_SUPERADMIN_LOGIN' && !value.trim()) {
    value = process.env.NODE_ENV === 'production' ? 'false' : 'true';
  }
  // AUTH / DESKTOP auth may be intentionally empty
  if (
    key !== 'REACT_APP_AUTH_API_URL' &&
    key !== 'REACT_APP_DESKTOP_AUTH_API_URL' &&
    key !== 'REACT_APP_SHOW_SUPERADMIN_LOGIN' &&
    !value.trim()
  ) {
    missing.push(key);
  }
  lines.push(`${key}=${value}`);
  console.log(
    `[write-frontend-env] ${key}=${
      key.includes('MERCHANT') || key.includes('USER_ID')
        ? value.trim()
          ? `(set, ${value.trim().length} chars)`
          : '(MISSING)'
        : value === ''
          ? '(empty)'
          : value
    }`
  );
}

if (!process.env.REACT_APP_DEFAULT_CENTER) {
  lines.push('REACT_APP_DEFAULT_CENTER=BRANCHLESS');
}

fs.writeFileSync(outFile, `${lines.join('\n')}\n`, 'utf8');
console.log('[write-frontend-env] wrote', outFile);

if (missing.length) {
  console.error(
    '\n[write-frontend-env] Missing build-time env vars:\n  ' +
      missing.join('\n  ') +
      '\n\nOn DigitalOcean → App → web → Environment Variables:\n' +
      '  • Scope must be Build Time or Run and Build Time (not Run only)\n' +
      '  • Prefer type “Plain” for REACT_APP_* (they are public in the JS bundle)\n' +
      '  • Then Actions → Force Rebuild and Deploy\n'
  );
  process.exit(1);
}
